namespace EiTRVO.Core.App.Services;

/// <summary>
/// 把"后台频繁报变更 → 界面刷新一次"合并成**每秒不超过固定次数**的刷新。
/// </summary>
/// <remarks>
/// 为什么需要它（AGENTS.md §6 的最后一条）：内核按 200ms 的窗口报进度，
/// 而界面上的表是 **24px 行高**的 —— 一行行刷新会卡；更糟的是"每来一条就刷一次"这件事
/// 在**生产端变啰嗦时**才会暴露：一个安装任务里有若干批次各自计时、阶段变更各发一次、
/// 再加 M6-f 之后事件入流也要通知界面，乘起来就是每秒十几次整表重建。
/// <para>
/// 语义三条（缺一条就会变成"界面永远停在上一帧"或"白刷"）：
/// </para>
/// <list type="number">
/// <item><b>首帧立即执行</b>：用户点了按钮、切了页面，界面必须当场反映，不能等一个窗口。</item>
/// <item><b>窗口内只跑一次</b>：窗口里的第 2…N 次请求只覆盖"待刷新"这一个动作，不排队。</item>
/// <item><b>尾帧必须送达</b>：窗口内的最后一次请求一定会被执行 ——
/// 下载完成/失败那一条往往就是"最后一条"，丢了它界面就永远停在 98%。</item>
/// </list>
/// <para>
/// 每个订阅者各有**一份实例**（注册为 transient）：合并的是"同一个刷新动作"，
/// 若全进程共用一个实例，页头的徽标与下载页的表格会互相顶掉对方的待刷新动作。
/// </para>
/// </remarks>
internal interface IUiRefreshThrottle
{
    /// <summary>
    /// 请求一次刷新：可能立即执行，也可能合并到窗口末尾执行（同一个动作被多次请求时只留最后一次）。
    /// </summary>
    /// <param name="refresh">刷新动作（在 UI 线程上执行）。</param>
    void Request(Action refresh);
}
